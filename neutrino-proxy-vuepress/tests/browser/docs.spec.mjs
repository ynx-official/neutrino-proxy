  await expect(sidebar.getByRole('link', { name: '1.x', exact: true })).toBeVisible()
  await expect(sidebar).not.toContainText('赞赏公示')

  await page.goto('./')
  await page.locator('.VPFooter').getByRole('link', { name: '历史站点资料', exact: true }).click()
